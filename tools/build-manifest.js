#!/usr/bin/env node
/*
 * Builds content/manifest.js: the light list of all units that the site loads at start.
 * Each unit's full file (lessons, exercises, quiz, lab) is then loaded only when a student
 * opens it. Also updates the manifest's ?v= version in index.html.
 *
 *   node tools/build-manifest.js           write content/manifest.js and update index.html
 *   node tools/build-manifest.js --check   only check that both are up to date (exit 1 if not)
 *
 * Run it after every change to a file in content/. Every content file is listed
 * automatically; the order on the site comes from each unit's `n`.
 */
'use strict';
const fs = require('fs'), vm = require('vm'), path = require('path'), crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');
const hash = s => crypto.createHash('sha1').update(s).digest('hex').slice(0, 10);

const ctx = { console }; ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'assets/core.js'), 'utf8'), ctx);

const entries = [];
const files = fs.readdirSync(path.join(root, 'content')).filter(f => /^cs\d+-u[\w-]+\.js$/.test(f)).sort();
for (const f of files) {
  const src = fs.readFileSync(path.join(root, 'content', f), 'utf8');
  const before = ctx.JP.units.length;
  vm.runInContext(src, ctx, { filename: f });
  const u = ctx.JP.units[before];
  if (!u || ctx.JP.units.length !== before + 1) { console.error(`${f}: must call JP.unit(...) exactly once`); process.exit(1); }
  const expected = `${u.course}-u${u.key || u.n}.js`;
  if (f !== expected) { console.error(`${f}: file name must be ${expected} (course + key)`); process.exit(1); }
  const e = {
    course: u.course, n: u.n, title: u.title, titleAr: u.titleAr, intro: u.intro, introAr: u.introAr,
    file: 'content/' + f, v: hash(src),
    lessons: (u.lessons || []).map(l => {
      const x = { title: l.title, titleAr: l.titleAr, minutes: l.minutes, practice: (l.practice || []).length };
      if (l.key != null) x.key = l.key;
      return x;
    }),
    quiz: (u.quiz || []).length,
    lab: u.lab ? { title: u.lab.title || '', titleAr: u.lab.titleAr || '' } : null
  };
  if (u.key != null) e.key = u.key;
  entries.push(e);
}
if (ctx.JP.errors.length) { console.error(ctx.JP.errors.join('\n')); process.exit(1); }

const manifest = '/* Generated by tools/build-manifest.js. Do not edit by hand: run `node tools/build-manifest.js`. */\n' +
  'JP.manifest([\n' + entries.map(e => JSON.stringify(e)).join(',\n') + '\n]);\n';
const mPath = path.join(root, 'content/manifest.js');
const iPath = path.join(root, 'index.html');
const html = fs.readFileSync(iPath, 'utf8');
const tag = `<script src="content/manifest.js?v=${hash(manifest)}"></script>`;
const re = /<script src="content\/manifest\.js(\?v=[\w]*)?"><\/script>/;
if (!re.test(html)) { console.error('index.html has no <script src="content/manifest.js..."> tag'); process.exit(1); }
const newHtml = html.replace(re, tag);

if (check) {
  const ok = fs.existsSync(mPath) && fs.readFileSync(mPath, 'utf8') === manifest && html === newHtml;
  console.log(ok ? 'manifest is up to date' : 'manifest is OUT OF DATE: run node tools/build-manifest.js');
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync(mPath, manifest);
fs.writeFileSync(iPath, newHtml);
const lessons = entries.reduce((a, e) => a + e.lessons.length, 0);
console.log(`content/manifest.js: ${entries.length} units, ${lessons} lessons, ${(manifest.length / 1024).toFixed(1)} KB. index.html updated.`);
