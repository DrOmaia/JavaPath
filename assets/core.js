/* JavaPath core: global registry + J`` helper. Loaded before every content file. */
(function () {
  'use strict';

  // String.raw with dedent + trim, so code blocks can be indented naturally in content files.
  function J(strings) {
    var subs = Array.prototype.slice.call(arguments, 1);
    var raw = String.raw.apply(null, [strings].concat(subs));
    var lines = raw.replace(/\r\n/g, '\n').split('\n');
    while (lines.length && !lines[0].trim()) lines.shift();
    while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
    var min = Infinity;
    lines.forEach(function (l) {
      if (l.trim()) min = Math.min(min, l.match(/^[ \t]*/)[0].length);
    });
    if (!isFinite(min)) min = 0;
    return lines.map(function (l) { return l.slice(min); }).join('\n');
  }

  var JP = window.JP = window.JP || {};
  JP.units = JP.units || [];
  JP.errors = JP.errors || [];

  function byId(id) {
    for (var i = 0; i < JP.units.length; i++) if (JP.units[i].id === id) return JP.units[i];
    return null;
  }

  // Called by every content file. If the unit was announced by the manifest, its stub is
  // filled in place, so every reference the app already holds sees the full content.
  JP.unit = function (u) {
    try {
      if (!u || !u.course || !u.n) throw new Error('unit needs course and n');
      // n = position shown to the student ("Unit 4") and used for ordering.
      // key = permanent storage id (file name, progress). Defaults to n. Keeping key fixed lets
      // units and lessons be re-ordered without losing anyone's saved progress.
      u.id = u.course + '-u' + (u.key || u.n);
      (u.lessons || []).forEach(function (l, i) { l.id = u.id + '-l' + (l.key || i + 1); l.n = i + 1; });
      var stub = byId(u.id);
      if (stub) { Object.assign(stub, u); stub.loaded = true; }
      else { u.loaded = true; JP.units.push(u); }
    } catch (e) {
      JP.errors.push(String(e));
    }
  };

  // Called once by content/manifest.js (generated by tools/build-manifest.js). Creates a light
  // stub for every unit: titles, lesson list, how many exercises and quiz questions, the lab
  // title. That is enough for the home, course and unit pages, progress and navigation.
  // practice and quiz are empty arrays of the right length until the unit file is loaded.
  JP.manifest = function (list) {
    (list || []).forEach(function (m) {
      var id = m.course + '-u' + (m.key || m.n);
      if (byId(id)) return;
      JP.units.push({
        course: m.course, key: m.key, n: m.n, id: id, file: m.file, v: m.v, loaded: false,
        title: m.title, titleAr: m.titleAr, intro: m.intro, introAr: m.introAr,
        lessons: (m.lessons || []).map(function (l, i) {
          return { key: l.key, id: id + '-l' + (l.key || i + 1), n: i + 1, title: l.title, titleAr: l.titleAr, minutes: l.minutes, practice: new Array(l.practice || 0) };
        }),
        quiz: new Array(m.quiz || 0),
        lab: m.lab || null
      });
    });
  };

  // Load the full content of the given units (only the ones not loaded yet). Resolves when all
  // are ready; rejects if a file cannot be loaded (for example, no internet).
  JP.load = function (units) {
    return Promise.all((units || []).filter(function (u) { return u && !u.loaded && u.file; }).map(function (u) {
      if (u.loading) return u.loading;
      u.loading = new Promise(function (resolve, reject) {
        var s = document.createElement('script');
        s.src = u.file + (u.v ? '?v=' + u.v : '');
        s.async = true;
        s.onload = function () {
          if (u.loaded) resolve(u);
          else { u.loading = null; reject(new Error(u.file + ' did not define ' + u.id)); }
        };
        s.onerror = function () { u.loading = null; s.remove(); reject(new Error('Could not load ' + u.file)); };
        document.head.appendChild(s);
      });
      return u.loading;
    }));
  };

  window.J = J;
})();
